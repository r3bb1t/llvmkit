#![forbid(unsafe_code)]

//! TableGen front end and intrinsic emitter.
//!
//! Ports two upstream subsystems, which is why this is its own crate rather
//! than a build script:
//!
//! - **The TableGen language front end** — `llvm/lib/TableGen/`: the lexer
//!   (`TGLexer.cpp`), the parser (`TGParser.cpp`), the record/value model
//!   (`Record.cpp`), errors (`Error.cpp`) and the driver (`Main.cpp`).
//! - **The intrinsic emitter** — `llvm/utils/TableGen/Basic/`:
//!   `CodeGenIntrinsics.cpp`'s per-intrinsic model and
//!   `IntrinsicEmitter.cpp`'s IIT type-signature encoding and table output.
//!
//! Upstream ships these as a library plus a `llvm-tblgen` binary. llvmkit does
//! the same: [`generate`] and [`verify_generated`] are the library entry
//! points — `llvmkit-ir`'s `build.rs` calls [`generate`] against
//! [`vendored_llvm_root`] and replays [`Generated::inputs`] as
//! `cargo:rerun-if-changed` lines — and [`table_gen_main`] drives the same
//! pair from the `llvmkit-tablegen` binary's command line.
//!
//! # Why a crate and not a build script
//!
//! It lived as `llvmkit-ir/tools/gen_intrinsics.rs`, included into `build.rs`
//! with `#[path]`. That shape had two costs. A build script is not a test
//! target, so its ten `#[test]` functions **never ran** under
//! `cargo test`, despite each carrying an `UPSTREAM.md` provenance row. And a
//! single 4,000-line file mirrored no upstream file, in a project whose
//! organising rule is that it mirrors LLVM's.
//!
//! # The vendored input
//!
//! `tablegen/llvm-22.1.4/` holds the `.td` files this expands. They live here,
//! with the generator that reads them, so [`VENDORED_LLVM_ROOT`] resolves
//! against this crate's own manifest directory.

