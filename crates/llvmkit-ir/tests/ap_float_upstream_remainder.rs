/// Port of the individual cases in `TEST(APFloatTest, remainder)`.
#[test]
fn upstream_remainder_cases() {
    let cases: Vec<(ApFloat, ApFloat, Option<&str>, S)> = vec![
        (
            parse_double("0x1.3333333333333p-2"),
            parse_double("0x1.47ae147ae147bp-7"),
            Some("-0x1.4p-56"),
            S::OK,
        ),
        (
            parse_double("0x1p64"),
            parse_double("1.5"),
            Some("-0.5"),
            S::OK,
        ),
        (
            parse_double("0x1p1000"),
            parse_double("0x1p-1000"),
            Some("0.0"),
            S::OK,
        ),
        (
            ApFloat::inf(DOUBLE, ApFloatSign::Positive),
            parse_double("1.0"),
            None,
            S::INVALID_OP,
        ),
        (
            parse_double("-4.0"),
            parse_double("-2.0"),
            Some("-0.0"),
            S::OK,
        ),
        (
            parse_double("-4.0"),
            parse_double("2.0"),
            Some("-0.0"),
            S::OK,
        ),
    ];
    for (i, (f1, f2, expected, status)) in cases.iter().enumerate() {
        let (got, got_status) = f1.remainder(f2);
        assert_eq!(got_status, *status, "remainder[{i}] status");
        match expected {
            Some(text) => assert!(
                parse_double(text).bitwise_is_equal(&got),
                "remainder[{i}]: expected {text}, got {got:?}"
            ),
            None => assert!(got.is_nan(), "remainder[{i}] should be NaN, got {got:?}"),
        }
    }
}

