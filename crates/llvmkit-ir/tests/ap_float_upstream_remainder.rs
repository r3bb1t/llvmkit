//! Ports of `TEST(APFloatTest, remainder)` and `TEST(APFloatTest, mod)` from
//! `llvm/unittests/ADT/APFloatTest.cpp` in the vendored `llvmorg-22.1.4` tree.
//!
//! `remainder`'s `SpecialCaseTests` table is ported the same way the
//! add/subtract/multiply/divide tables are: operands built as the fixture
//! builds them, the expected value constructed from the string the table
//! spells, and `bitwiseIsEqual` plus status and category asserted. The
//! individual `{ f1; f2; expected }` blocks that follow each test are ported
//! one assertion at a time.
//!
//! Generated from the C++ tables; regenerate rather than hand-edit.

use llvmkit_ir::{
    ApFloat, ApFloatCategory as C, ApFloatSemantics, ApFloatSign, ApFloatStatus as S, NanPayload,
    RoundingMode,
};

const SINGLE: ApFloatSemantics = ApFloatSemantics::IeeeSingle;
const DOUBLE: ApFloatSemantics = ApFloatSemantics::IeeeDouble;
const NEAREST: RoundingMode = RoundingMode::NearestTiesToEven;

fn parse(text: &str) -> ApFloat {
    ApFloat::from_string(SINGLE, text, NEAREST)
        .unwrap_or_else(|e| panic!("upstream spells {text:?}, which must parse: {e}"))
        .0
}

fn parse_double(text: &str) -> ApFloat {
    ApFloat::from_string(DOUBLE, text, NEAREST)
        .unwrap_or_else(|e| panic!("upstream spells {text:?}, which must parse: {e}"))
        .0
}

