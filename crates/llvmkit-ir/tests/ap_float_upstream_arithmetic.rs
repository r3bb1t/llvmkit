//! Port of the `APFloat` special-case arithmetic tables from
//! `llvm/unittests/ADT/APFloatTest.cpp` — `TEST(APFloatTest, add)`,
//! `subtract`, `multiply`, and `divide` — in the vendored `llvmorg-22.1.4`
//! tree. 196 rows each: every pairing of the fourteen special and boundary
//! `IEEEsingle` values against each other.
//!
//! Ported verbatim. Each operand is built the way the upstream fixture builds
//! it (`getInf`, `getNaN`, `getLargest`, `getSmallest`,
//! `getSmallestNormalized`, or the string constructor), the expected result is
//! constructed from the same string the upstream table spells, and the
//! comparison is `bitwiseIsEqual` plus the status flags and the category —
//! exactly the three assertions in the upstream loop.
//!
//! Generated from the C++ table; regenerate rather than hand-edit.

use llvmkit_ir::{
    ApFloat, ApFloatCategory as C, ApFloatSemantics, ApFloatSign, ApFloatStatus as S, NanPayload,
    RoundingMode,
};

const SINGLE: ApFloatSemantics = ApFloatSemantics::IeeeSingle;

/// The fourteen values the upstream fixture declares before its table.
#[derive(Clone, Copy, Debug)]
enum Op {
    PInf,
    MInf,
    PZero,
    MZero,
    QNaN,
    SNaN,
    PNormalValue,
    MNormalValue,
    PLargestValue,
    MLargestValue,
    PSmallestValue,
    MSmallestValue,
    PSmallestNormalized,
    MSmallestNormalized,
}

fn parse(text: &str) -> ApFloat {
    ApFloat::from_string(SINGLE, text, RoundingMode::NearestTiesToEven)
        .unwrap_or_else(|e| panic!("upstream spells {text:?}, which must parse: {e}"))
        .0
}

fn build(op: Op) -> ApFloat {
    match op {
        Op::PInf => ApFloat::inf(SINGLE, ApFloatSign::Positive),
        Op::MInf => ApFloat::inf(SINGLE, ApFloatSign::Negative),
        Op::PZero => ApFloat::zero(SINGLE, ApFloatSign::Positive),
        Op::MZero => ApFloat::zero(SINGLE, ApFloatSign::Negative),
        Op::QNaN => ApFloat::qnan(SINGLE, ApFloatSign::Positive, NanPayload::Absent),
        Op::SNaN => parse("snan123"),
        Op::PNormalValue => parse("0x1p+0"),
        Op::MNormalValue => parse("-0x1p+0"),
        Op::PLargestValue => ApFloat::largest(SINGLE, ApFloatSign::Positive),
        Op::MLargestValue => ApFloat::largest(SINGLE, ApFloatSign::Negative),
        Op::PSmallestValue => ApFloat::smallest(SINGLE, ApFloatSign::Positive),
        Op::MSmallestValue => ApFloat::smallest(SINGLE, ApFloatSign::Negative),
        Op::PSmallestNormalized => ApFloat::smallest_normalized(SINGLE, ApFloatSign::Positive),
        Op::MSmallestNormalized => ApFloat::smallest_normalized(SINGLE, ApFloatSign::Negative),
    }
}

struct Row {
    x: Op,
    y: Op,
    result: &'static str,
    status: S,
    category: C,
}

/// The upstream loop body: apply, then assert `bitwiseIsEqual`, the status,
/// and the category. Failures are collected so one run reports the whole
/// divergence set rather than only the first row.
fn check(name: &str, rows: &[Row], apply: fn(&ApFloat, &ApFloat) -> (ApFloat, S)) {
    let mut failures = Vec::new();
    for (i, row) in rows.iter().enumerate() {
        let x = build(row.x);
        let y = build(row.y);
        let (got, status) = apply(&x, &y);
        let result = parse(row.result);
        if !result.bitwise_is_equal(&got) || status != row.status || got.category() != row.category
        {
            failures.push(format!(
                "{name}[{i}] {:?} {:?}: expected {} {:?} {:?}, got {got:?} {status:?} {:?}",
                row.x,
                row.y,
                row.result,
                row.status,
                row.category,
                got.category(),
            ));
        }
    }
    assert!(
        failures.is_empty(),
        "{} of {} upstream {name} rows diverge:\n{}",
        failures.len(),
        rows.len(),
        failures.join("\n")
    );
}

