//! LLVM's own `APFloat` special-case arithmetic tables, transcoded.
//!
//! Every row is a verbatim port of one entry in the `SpecialCaseTests` arrays
//! of `llvm/unittests/ADT/APFloatTest.cpp` (`TEST(APFloatTest, add)`,
//! `subtract`, `multiply`, `divide` in the vendored `llvmorg-22.1.4` tree) —
//! 784 rows covering every pairing of the fourteen special and boundary
//! `IEEEsingle` values against each other.
//!
//! The expected result is stored as an exact bit pattern rather than as the
//! upstream spelling, so the oracle does not route through llvmkit's own
//! string parser; the upstream spelling is kept beside it for provenance and
//! for diffing against the C++ table. Bit patterns were derived from the
//! upstream spellings by `float.fromhex` at generation time, each checked to
//! round-trip through `f32` without rounding.
//!
//! Generated file — regenerate rather than hand-edit if upstream changes.

use llvmkit_ir::{
    ApFloat, ApFloatCategory as C, ApFloatSemantics, ApFloatSign, ApFloatStatus as S, ApInt,
    NanPayload, RoundingMode,
};

const SINGLE: ApFloatSemantics = ApFloatSemantics::IeeeSingle;

#[derive(Clone, Copy, Debug)]
enum Op {
    PInf,
    MInf,
    PZero,
    MZero,
    QNaN,
    SNaN,
    PNormal,
    MNormal,
    PLargest,
    MLargest,
    PSmallest,
    MSmallest,
    PSmallestNormalized,
    MSmallestNormalized,
}

/// Builds each operand from a bit pattern or a typed constructor — never from
/// a string — so a parser defect cannot mask an arithmetic defect.
fn build(op: Op) -> ApFloat {
    let bits = |b: u32| {
        ApFloat::from_bits(SINGLE, &ApInt::from_words(32, &[u64::from(b)]))
            .expect("32-bit pattern is valid for IEEEsingle")
    };
    match op {
        Op::PInf => ApFloat::inf(SINGLE, ApFloatSign::Positive),
        Op::MInf => ApFloat::inf(SINGLE, ApFloatSign::Negative),
        Op::PZero => ApFloat::zero(SINGLE, ApFloatSign::Positive),
        Op::MZero => ApFloat::zero(SINGLE, ApFloatSign::Negative),
        Op::QNaN => ApFloat::qnan(SINGLE, ApFloatSign::Positive, NanPayload::Absent),
        // Upstream spells this `APFloat(IEEEsingle, "snan123")`: a signaling
        // NaN with payload 123, i.e. quiet bit clear, payload in the low bits.
        Op::SNaN => bits(0x7f80_0000 | 123),
        Op::PNormal => bits(0x3f80_0000),
        Op::MNormal => bits(0xbf80_0000),
        Op::PLargest => ApFloat::largest(SINGLE, ApFloatSign::Positive),
        Op::MLargest => ApFloat::largest(SINGLE, ApFloatSign::Negative),
        Op::PSmallest => ApFloat::smallest(SINGLE, ApFloatSign::Positive),
        Op::MSmallest => ApFloat::smallest(SINGLE, ApFloatSign::Negative),
        Op::PSmallestNormalized => ApFloat::smallest_normalized(SINGLE, ApFloatSign::Positive),
        Op::MSmallestNormalized => ApFloat::smallest_normalized(SINGLE, ApFloatSign::Negative),
    }
}

struct Row {
    x: Op,
    y: Op,
    /// The upstream spelling, kept for provenance.
    spelling: &'static str,
    expected: u32,
    status: S,
    category: C,
}

fn check(op_name: &str, rows: &[Row], apply: fn(&ApFloat, &ApFloat) -> (ApFloat, S)) {
    let mut failures = Vec::new();
    for (i, row) in rows.iter().enumerate() {
        let (result, status) = apply(&build(row.x), &build(row.y));
        let got = result
            .to_bits()
            .try_zext_u64()
            .expect("IEEEsingle bits fit in u64") as u32;
        if got != row.expected || status != row.status || result.category() != row.category {
            failures.push(format!(
                "{op_name}[{i}] {:?} {op_name} {:?}: expected {} (0x{:08x}) {:?} {:?}, \
                 got 0x{got:08x} {status:?} {:?}",
                row.x,
                row.y,
                row.spelling,
                row.expected,
                row.status,
                row.category,
                result.category(),
            ));
        }
    }
    assert!(
        failures.is_empty(),
        "{} of {} upstream {op_name} rows diverge:\n{}",
        failures.len(),
        rows.len(),
        failures.join("\n")
    );
}

